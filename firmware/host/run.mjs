// Builds and runs the firmware's host tests: writes build/vectors.h from protocol/vectors.json, compiles
// host/*.cpp with firmware/lib/proto using g++ (WinLibs, on PATH), and runs the result.
// Usage, from the repo root: node firmware/host/run.mjs
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..', '..');
const libDir = path.join(root, 'firmware', 'lib', 'proto', 'src');
const uiDir = path.join(root, 'firmware', 'lib', 'ui', 'src'); // the screen logic, as pure as the protocol is
const buildDir = path.join(here, 'build');
mkdirSync(buildDir, { recursive: true });

const v = JSON.parse(readFileSync(path.join(root, 'protocol', 'vectors.json'), 'utf8'));
const sv = JSON.parse(readFileSync(path.join(root, 'protocol', 'seal-vectors.json'), 'utf8'));
const str = (s) => JSON.stringify(s); // the vectors' strings are ASCII, so a JSON string is a valid C literal
const list = (items) => items.join(',\n  ');
writeFileSync(path.join(buildDir, 'vectors.h'), `// Generated by firmware/host/run.mjs from protocol/vectors.json. Do not edit.
#pragma once
#include <stdint.h>
struct HexU32 { const char* hex; uint32_t value; };
struct CobsVec { const char* decoded; const char* encoded; };
struct FrameVec { const char* name; uint8_t type; uint8_t flags; uint16_t seq; const char* payload; const char* wire; };
struct StreamVec { const char* name; const char* chunks; const char* expect; int bad; };
struct MsgVec { const char* name; const char* hex; };
struct HkdfVec { const char* name; const char* ikm; const char* salt; const char* info; int length; const char* okm; };
struct AdpcmVec { const char* name; const char* pcm; uint8_t indexIn; const char* frame; uint8_t indexOut; const char* decoded; };
struct RoomVec { const char* master; const char* id; };
struct SealVec { uint8_t dir; uint8_t type; uint8_t flags; uint16_t seq; uint32_t counter; const char* plain; const char* envelope; };
static const HexU32 kCrc16[] = {
  ${list(v.crc16.map((c) => `{${str(c.hex)}, ${c.crc}u}`))}};
static const HexU32 kCrc32[] = {
  ${list(v.crc32.map((c) => `{${str(c.hex)}, ${c.crc}u}`))}};
static const CobsVec kCobs[] = {
  ${list(v.cobs.map((c) => `{${str(c.decoded)}, ${str(c.encoded)}}`))}};
static const char* const kCobsInvalid[] = {${v.cobsInvalid.map(str).join(', ')}};
static const FrameVec kFrames[] = {
  ${list(v.frames.map((f) => `{${str(f.name)}, ${f.type}, ${f.flags}, ${f.seq}, ${str(f.payload)}, ${str(f.wire)}}`))}};
static const StreamVec kStreams[] = {
  ${list(v.streams.map((s) => `{${str(s.name)}, ${str(s.chunks.join(','))}, ${str(s.expect)}, ${s.bad}}`))}};
static const MsgVec kMsgs[] = {
  ${list(v.messages.map((m) => `{${str(m.name)}, ${str(m.hex)}}`))}};
static const HkdfVec kHkdf[] = {
  ${list(sv.hkdf.map((k) => `{${str(k.name)}, ${str(k.ikm)}, ${str(k.salt)}, ${str(k.info)}, ${k.length}, ${str(k.okm)}}`))}};
static const char* const kSealMaster = ${str(sv.session.master)};
static const uint32_t kSealNonceP = ${sv.session.nonceP}u;
static const uint32_t kSealNonceS = ${sv.session.nonceS}u;
static const SealVec kSealFrames[] = {
  ${list(sv.frames.map((f) => `{${f.dir}, ${f.type}, ${f.flags}, ${f.seq}, ${f.counter}u, ${str(f.plain)}, ${str(f.envelope)}}`))}};
static const char* const kRoomInfo = ${str(sv.room.info)};
static const RoomVec kRooms[] = {
  ${list(sv.room.cases.map((r) => `{${str(r.master)}, ${str(r.id)}}`))}};
static const uint32_t kReplayCounters[] = {${sv.replay.counters.map((c) => `${c}u`).join(', ')}};
static const uint8_t kReplayAccepted[] = {${sv.replay.accepted.join(', ')}};
static const int16_t kAdpcmSteps[] = {${v.adpcm.steps.join(', ')}};
static const int8_t kAdpcmIndex[] = {${v.adpcm.indexTable.join(', ')}};
static const AdpcmVec kAdpcm[] = {
  ${list(v.adpcm.cases.map((c) => `{${str(c.name)}, ${str(c.pcm)}, ${c.indexIn}, ${str(c.frame)}, ${c.indexOut}, ${str(c.decoded)}}`))}};
static const char* const kPatternFirst8 = ${str(v.pattern.first8)};
static const uint16_t kPatternAt80000 = ${v.pattern.at80000};
`);

const cpp = (dir) => (existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.cpp')).map((f) => path.join(dir, f)) : []);
const exe = path.join(buildDir, 'test_proto.exe');
// test_audio.cpp includes firmware/src/audio.cpp itself, against the stubs in host/stubs.
const cc = spawnSync('g++', ['-std=gnu++11', '-O1', '-Wall', '-Wextra', '-Werror', `-I${libDir}`, `-I${uiDir}`, `-I${buildDir}`,
  `-I${path.join(here, 'stubs')}`, `-I${path.join(root, 'firmware', 'src')}`,
  ...cpp(here), ...cpp(path.join(libDir, 'proto')), ...cpp(path.join(uiDir, 'ui')), '-o', exe], { stdio: 'inherit' });
if (cc.error || cc.status !== 0) {
  console.error(cc.error ? `g++ could not start: ${cc.error.message}` : 'compile failed');
  process.exit(1);
}
const run = spawnSync(exe, [], { stdio: 'inherit' });
if (run.error) {
  console.error(`could not run ${exe}: ${run.error.message}`);
  process.exit(1);
}
process.exit(run.status ?? 1);
